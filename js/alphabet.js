const ORDER = "АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ";

// Список всех 33 букв по алфавиту: { letter, status, description, lesson }.
export const ALPHABET = [...ORDER].map((letter) => {
  if (LETTERS[letter]) {
    return { letter, status: "yes", description: LETTERS[letter].description, lesson: LETTERS[letter].lesson };
  }
  const [status, description] = EXTRA[letter];
  return { letter, status, description, lesson: null };
});

